static void nv21_fill_rect(uint8_t *yp, uint8_t *uvp, uint32_t stride, int w, int h, int x0, int y0,
                           int x1, int y1, uint8_t Y, uint8_t U, uint8_t V) {
  if (x0 < 0) x0 = 0;
  if (y0 < 0) y0 = 0;
  if (x1 > w - 1) x1 = w - 1;
  if (y1 > h - 1) y1 = h - 1;
  if (x0 > x1 || y0 > y1) return;

  for (int y = y0; y <= y1; y++) {
    uint8_t *row = yp + (size_t)y * stride;
    uint8_t *uvrow = (uvp != NULL) ? uvp + (size_t)(y >> 1) * stride : NULL;
    for (int x = x0; x <= x1; x++) {
      row[x] = Y;
      if (uvrow != NULL) {
        uint8_t *uv = uvrow + (size_t)(x & ~1);
        uv[0] = V;
        uv[1] = U;
      }
    }
  }
}

void nv21_draw_rect(uint8_t *yp, uint8_t *uvp, uint32_t stride, int w, int h, int x0, int y0,
                    int x1, int y1, int thickness, uint8_t Y, uint8_t U, uint8_t V) {
  if (thickness < 1) thickness = 1;
  for (int t = 0; t < thickness; t++) {
    nv21_fill_rect(yp, uvp, stride, w, h, x0 + t, y0 + t, x1 - t, y0 + t, Y, U, V);
    nv21_fill_rect(yp, uvp, stride, w, h, x0 + t, y1 - t, x1 - t, y1 - t, Y, U, V);
    nv21_fill_rect(yp, uvp, stride, w, h, x0 + t, y0 + t, x0 + t, y1 - t, Y, U, V);
    nv21_fill_rect(yp, uvp, stride, w, h, x1 - t, y0 + t, x1 - t, y1 - t, Y, U, V);
  }
}

static void nv21_draw_char(uint8_t *yp, uint8_t *uvp, uint32_t stride, int w, int h, int x, int y,
                           char ch, int scale, uint8_t Y, uint8_t U, uint8_t V) {
  if (ch < 32 || ch >= 127) return;
  const uint8_t *glyph = k_font5x7[(int)ch - 32];
  for (int col = 0; col < 5; col++) {
    for (int row = 0; row < 7; row++) {
      if (glyph[col] & (1 << row)) {
        nv21_fill_rect(yp, uvp, stride, w, h, x + col * scale, y + row * scale,
                       x + col * scale + scale - 1, y + row * scale + scale - 1, Y, U, V);
      }
    }
  }
}

void nv21_draw_text(uint8_t *yp, uint8_t *uvp, uint32_t stride, int w, int h, int x, int y,
                    const char *text, int scale, uint8_t Y, uint8_t U, uint8_t V) {
  if (scale < 1) scale = 1;
  for (const char *p = text; *p != '\0'; p++) {
    nv21_draw_char(yp, uvp, stride, w, h, x, y, *p, scale, Y, U, V);
    x += 6 * scale;
  }
}
